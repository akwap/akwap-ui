"""Write a CSS file that points Tailwind at the installed AkwapUI package.

    python manage.py akwapui_tailwind            # -> assets/css/akwapui.css
    python manage.py akwapui_tailwind -o styles/akwapui.css

Import the result from your Tailwind entry file, after Tailwind itself:

    @import "tailwindcss";
    @import "./akwapui.css";
    @source "../../templates";

The paths are relative to where AkwapUI is installed on this machine, so
regenerate the file after installing (and keep it out of version control).
"""

import os
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand

import akwapui_django


class Command(BaseCommand):
    help = "Generate the Tailwind import for AkwapUI's tokens, themes, utilities and component classes."

    def add_arguments(self, parser):
        parser.add_argument("-o", "--output", default="assets/css/akwapui.css", help="Path of the file to write (relative to BASE_DIR).")

    def handle(self, *args, output, **options):
        base = Path(getattr(settings, "BASE_DIR", os.getcwd()))
        out = Path(output)
        if not out.is_absolute():
            out = base / out
        out.parent.mkdir(parents=True, exist_ok=True)
        pkg = Path(akwapui_django.__file__).resolve().parent

        def rel(p: Path) -> str:
            return Path(os.path.relpath(p, out.parent.resolve())).as_posix()

        out.write_text(
            "/* Generated by `python manage.py akwapui_tailwind`. Do not edit or commit. */\n"
            f"@import '{rel(pkg / 'tailwind' / 'theme.css')}';\n"
            f"@source '{rel(pkg / 'templates')}';\n"
            f"@source '{rel(pkg / 'static' / 'akwapui' / 'akwapui.js')}';\n"
        )
        self.stdout.write(self.style.SUCCESS(f"Wrote {out}"))
